#!/usr/bin/env bash
# Device-level exposure: the debugging surfaces and platform integrity signals
# that decide whether anything else here matters.

register_setting_control \
    --id DEV-001 \
    --name 'Disable USB debugging' \
    --category Device \
    --tier baseline \
    --capability shell \
    --counters 'adb shell, PhoneSploit, Metasploit android/meterpreter staging, juice jacking' \
    --rationale 'ADB over USB is a full shell on the device for anyone who can plug into it and get the key accepted. It is the single most abused Android entry point in a pen-test kit.' \
    --tags 'device adb debugging' \
    --data 'settings=global adb_enabled 0' \
    --data 'unset_ok=1'

register_setting_control \
    --id DEV-002 \
    --name 'Disable wireless debugging' \
    --category Device \
    --tier baseline \
    --capability shell \
    --counters 'adb connect over Wi-Fi, PhoneSploit-Pro, mass 5555 internet scanning' \
    --rationale 'Wireless debugging exposes ADB to the whole network segment rather than to a cable. Internet-wide scans for open 5555 have been running continuously for years.' \
    --tags 'device adb debugging' \
    --data 'settings=global adb_wifi_enabled 0' \
    --data 'unset_ok=1'

register_setting_control \
    --id DEV-003 \
    --name 'Turn off developer options' \
    --category Device \
    --tier standard \
    --capability shell \
    --counters 'adb re-enablement, mock locations, bugreport extraction' \
    --rationale 'Closing developer options removes the one-tap route back to debugging and to the other settings this toolkit just turned off.' \
    --tags 'device debugging' \
    --data 'settings=global development_settings_enabled 0' \
    --data 'unset_ok=1'

register_setting_control \
    --id DEV-004 \
    --name 'Keep Play Protect package verification on' \
    --category Device \
    --tier baseline \
    --capability shell \
    --counters 'msfvenom APK payloads, AhMyth, L3MON, sideloaded RATs' \
    --rationale 'Package verification scans sideloaded APKs before install. It is the one check standing between a payload generated by msfvenom and an installed RAT.' \
    --tags 'device malware' \
    --data 'settings=global package_verifier_enable 1
global package_verifier_user_consent 1'

# ---------------------------------------------------------------------------
# Platform integrity (audit only, no privilege needed)
# ---------------------------------------------------------------------------
# These cannot be fixed by a script. Reporting them honestly is still worth
# doing, because every control above is only as trustworthy as the platform
# underneath it.

dev_bootloader_test() {
    local locked unlock_allowed
    locked="$(sys_getprop ro.boot.flash.locked)"
    unlock_allowed="$(sys_getprop sys.oem_unlock_allowed)"

    if [ -z "$locked" ] && [ -z "$unlock_allowed" ]; then
        verdict_unknown 'the bootloader properties are not readable on this device'
        return 0
    fi
    if [ "$locked" = '1' ] && [ "$unlock_allowed" != '1' ]; then
        verdict_ok 'bootloader locked and OEM unlocking disallowed'
        return 0
    fi
    verdict_bad "bootloader locked=${locked:-unknown}, OEM unlocking allowed=${unlock_allowed:-unknown}. An unlocked bootloader lets anyone with the device and a USB cable flash a modified boot image, which defeats every software control on this list."
}

register_control \
    --id DEV-005 \
    --name 'Bootloader lock state' \
    --category Device \
    --tier baseline \
    --capability none \
    --test dev_bootloader_test \
    --audit-only \
    --counters 'fastboot boot, custom recovery, physical-access image replacement' \
    --rationale 'Read-only check. Relocking a bootloader wipes the device, so this toolkit reports the state and leaves the decision to you.' \
    --tags 'device integrity audit'

dev_verifiedboot_test() {
    local state
    state="$(sys_getprop ro.boot.verifiedbootstate)"
    case "$state" in
        green)  verdict_ok 'verified boot is green (stock, signed, untampered)' ;;
        yellow) verdict_bad 'verified boot is yellow: the device boots a custom key. Expected if you flashed a signed custom ROM, otherwise investigate.' ;;
        orange) verdict_bad 'verified boot is orange: verification is off entirely. The boot image is not being checked.' ;;
        red)    verdict_bad 'verified boot is red: the boot image failed verification. Treat this device as compromised.' ;;
        *)      verdict_unknown 'verified boot state is not reported by this device' ;;
    esac
}

register_control \
    --id DEV-006 \
    --name 'Verified boot state' \
    --category Device \
    --tier baseline \
    --capability none \
    --test dev_verifiedboot_test \
    --audit-only \
    --counters 'modified boot images, persistent rootkits, Magisk-based implants' \
    --rationale 'Reports what the bootloader concluded about the running boot image. Nothing in userspace can fix a bad answer here.' \
    --tags 'device integrity audit'

dev_selinux_test() {
    local mode=''
    if sys_have getenforce; then
        mode="$(sys_run getenforce 2>/dev/null || true)"
    fi
    [ -n "$mode" ] || mode="$(sys_read_file /sys/fs/selinux/enforce)"

    case "$mode" in
        Enforcing|1) verdict_ok 'SELinux is enforcing' ;;
        Permissive|0) verdict_bad 'SELinux is permissive: policy violations are logged but allowed, so app sandbox escapes that would normally be blocked will succeed.' ;;
        *) verdict_unknown 'SELinux mode is not readable from this shell' ;;
    esac
}

register_control \
    --id DEV-007 \
    --name 'SELinux enforcing' \
    --category Device \
    --tier baseline \
    --capability none \
    --test dev_selinux_test \
    --audit-only \
    --counters 'sandbox escapes, local privilege escalation chains, dirtycow-style exploits' \
    --rationale 'SELinux in permissive mode is the difference between an exploit being contained and an exploit working. Usually only turned off deliberately on a modified device.' \
    --tags 'device integrity audit'

dev_patch_test() {
    local patch today age_days
    patch="$(sys_getprop ro.build.version.security_patch)"
    [ -n "$patch" ] || { verdict_unknown 'the security patch level is not reported'; return 0; }

    today="$(date +%s)"
    local patch_epoch
    patch_epoch="$(date -d "$patch" +%s 2>/dev/null || echo '')"
    [ -n "$patch_epoch" ] || { verdict_unknown "security patch level $patch could not be parsed"; return 0; }

    age_days=$(( (today - patch_epoch) / 86400 ))
    if [ "$age_days" -le 120 ]; then
        verdict_ok "security patch $patch (${age_days} days old)"
    else
        verdict_bad "security patch $patch is ${age_days} days old. Public exploits for Android bugs are usually available well inside that window, and searchsploit ships them."
    fi
}

register_control \
    --id DEV-008 \
    --name 'Security patch level freshness' \
    --category Device \
    --tier baseline \
    --capability none \
    --test dev_patch_test \
    --audit-only \
    --counters 'searchsploit, Metasploit android exploit modules, public n-day chains' \
    --rationale 'An unpatched phone is attacked with published exploits, not clever ones. This reports how far behind the device is; only the vendor can fix it.' \
    --tags 'device patching audit'
